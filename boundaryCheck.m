%%
% BoundaryCheck 边界检查函数
% 保证输入的矩阵X每个元素都在给定的上下界 [lb, ub] 范围内，超界则拉回边界
%
% 输入参数：
%   X  ：待检查的矩阵（粒子群、解向量等，每行为一个个体）
%   lb ：下界（可以是标量或与X同维向量）
%   ub ：上界（可以是标量或与X同维向量）
%
% 输出参数：
%   X  ：边界修正后的矩阵

function [ X ] = BoundaryCheck(X, lb, ub)
    % 遍历X的每一行（每个个体/粒子）
    for i = 1:size(X,1)
        FU = X(i,:) > ub;   % 超上界的元素标记为1
        FL = X(i,:) < lb;   % 超下界的元素标记为1
        % 对每一维：
        % - 没有超界的保持原值
        % - 超上界的赋为ub
        % - 超下界的赋为lb
        X(i,:) = (X(i,:) .* (~(FU+FL))) + ub .* FU + lb .* FL;
    end
end